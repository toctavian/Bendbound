// Generate the server's copy of the app's pure geometry helpers. No mobile runtime
// dependencies enter the container. --check catches drift in CI/tests.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/utils/routes.ts'), 'utf8');
const wanted = new Set(['distanceBetween', 'routeDistance', 'pointAtBearing', 'decodePolyline', 'roadCells', 'sharedRoadInterval', 'repeatedRoadRatio', 'splitSharedAccess', 'roundTripRoadUse']);
const ast = ts.createSourceFile('routes.ts', source, ts.ScriptTarget.Latest, true);
const functions = ast.statements.filter(node => ts.isFunctionDeclaration(node) && wanted.has(node.name.text))
  .map(node => node.getText(ast).replace(/^(?!export )/, 'export ')).join('\n');
const constants = 'const earthRadiusKm = 6371; const overlapToleranceMetres = 0.5; const roadCellMetres = 100;\n';
const output = '// Generated by routing/build-geometry.cjs from src/utils/routes.ts. Do not edit.\n' + ts.transpileModule(constants + functions, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
}).outputText;
const target = path.join(__dirname, 'service/geometry.mjs');
fs.mkdirSync(path.dirname(target), { recursive: true });
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node routing/build-geometry.cjs to refresh server geometry.');
} else fs.writeFileSync(target, output);
